import unittest
from unittest.mock import MagicMock

from eval.rubric import load_rubric
from eval.metrics import (
    check_required_terms,
    check_forbidden_phrases,
    check_length_bounds,
    check_citation_preservation,
    check_latex_compile_success,
    check_section_heading_presence,
    check_idea_coverage
)

class TestMaskedSectionEval(unittest.TestCase):
    def setUp(self):
        self.rubric = load_rubric("tests/fixtures/rubrics/methodology_missing.yaml")
        with open("tests/fixtures/gold/03_approach.tex", "r") as f:
            self.gold_text = f.read()
            
        # In a real run, this would be generated by the LLM
        self.generated_text = self.gold_text 

    def test_reconstruction_rubric(self):
        # 1. Idea coverage (mocked to 1.0 if identical)
        coverage = check_idea_coverage(self.generated_text, self.gold_text, self.rubric.required_ideas)
        self.assertGreaterEqual(coverage, 0.8, "Idea coverage below 4/5")
        
        # 2. Terminology consistency
        term_score = check_required_terms(self.generated_text, self.rubric.required_terms)
        self.assertGreaterEqual(term_score, 0.8, "Terminology consistency below 4/5")
        
        # 3. Unsupported claims (forbidden phrases)
        unsupported = check_forbidden_phrases(self.generated_text, self.rubric.forbidden_claims)
        self.assertLessEqual(unsupported, 1, "Too many unsupported claims")
        
        # 4. Other constraints
        self.assertTrue(check_length_bounds(self.generated_text), "Length out of bounds")
        self.assertTrue(check_latex_compile_success(self.generated_text), "LaTeX compilation failed")
        self.assertTrue(check_section_heading_presence(self.generated_text), "Missing section heading")
        
if __name__ == '__main__':
    unittest.main()
